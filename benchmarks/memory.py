"""How GPU memory limits Sagittal's batch size g, and what that does to per-proof cost.

Sagittal's tables hold (2^g - 1)/g points per input point, so on a fixed-memory GPU the batch
size g must shrink as n grows, and per-proof work per point grows with it. Pippenger's cost per
point instead falls with n. For each GPU memory size this finds the largest g whose tables,
points and scalars fit, capped by the GPU kernel's shared-memory limit (one batch's 2^g-entry
table in 48 KB), and reports per-proof field multiplications per point (XYZZ). All counts are
from the closed-form model, which tests check against measured counts. Writes:

- memory.csv   every size and memory budget: g, device memory, per-proof field multiplications
- memory.md    Markdown table of the same
- memory.png   per-proof field multiplications per point vs. n

Usage: uv run python benchmarks/memory.py [--curve bls12-377]
"""

import argparse
import csv
from dataclasses import dataclass
from pathlib import Path

from sagittal_msm import memory, model
from sagittal_msm.costs import per_proof_multiplications
from sagittal_msm.groups.curves import CURVES
from sagittal_msm.groups.weierstrass import CurveParams

# Chart colors: categorical slots 1-3 and text/surface tokens of the dataviz reference palette
# (validated as a set, light mode). Text never wears a series color.
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]
SURFACE = "#fcfcfb"
TEXT_PRIMARY = "#0b0b0b"
TEXT_SECONDARY = "#52514e"
GRID = "#e4e3df"

BUDGETS_GIB = [16, 24, 48]  # V100, A10G / L4, A40
CHARTED_GIB = [16, 48]
COORDS = "xyzz"


@dataclass
class Row:
    log_n: int
    budget_gib: int
    memory_g: int  # largest g that fits in memory
    g: int  # after the shared-memory cap
    device_gib: float
    sagittal_mults: float
    pippenger_c: int
    pippenger_mults: float


def compute(curve: CurveParams, log_ns: range) -> list[Row]:
    shared_cap = memory.max_shared_memory_batch_size(curve.p)
    rows = []
    for log_n in log_ns:
        n = 1 << log_n
        c = model.best_pippenger(n, curve.r, signed=True)
        pip = per_proof_multiplications(model.pippenger(n, curve.r, c, True), COORDS) / n
        for budget in BUDGETS_GIB:
            memory_g = memory.max_batch_size(n, budget * memory.GIB, curve.p, curve.r)
            g = min(memory_g, shared_cap)
            sag = per_proof_multiplications(model.sagittal(n, curve.r, g), COORDS) / n if g else 0
            device = memory.sagittal_device_bytes(n, g, curve.p, curve.r) / memory.GIB if g else 0
            rows.append(Row(log_n, budget, memory_g, g, device, sag, c, pip))
    return rows


def write_csv(path: Path, rows: list[Row]) -> None:
    with path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(
            [
                "log_n",
                "budget_gib",
                "memory_g",
                "g",
                "device_gib",
                "sagittal_mults_per_point",
                "pippenger_c",
                "pippenger_mults_per_point",
            ]
        )
        for r in rows:
            writer.writerow(
                [
                    r.log_n,
                    r.budget_gib,
                    r.memory_g,
                    r.g,
                    round(r.device_gib, 2),
                    round(r.sagittal_mults, 1),
                    r.pippenger_c,
                    round(r.pippenger_mults, 1),
                ]
            )


def write_markdown(path: Path, rows: list[Row], curve: CurveParams) -> None:
    shared_cap = memory.max_shared_memory_batch_size(curve.p)
    sizes = sorted({r.log_n for r in rows})
    lines = [
        f"Sagittal batch size under GPU memory limits, {curve.name} "
        f"({memory.affine_bytes(curve.p)}-byte affine points). "
        "Generated by `benchmarks/memory.py`.",
        "",
        "- **g** is the largest batch size whose tables, input points and one proof's scalars fit "
        f"in GPU memory, capped at {shared_cap}: one batch's 2^g-entry table must fit in 48 KB "
        "of shared memory for the GPU kernel. Memory-only limits are in parentheses when higher.",
        "- **Field mults** are per-proof field multiplications per point (XYZZ, mul + sqr), from "
        "the closed-form model. Pippenger (signed digits, best c) needs no extra memory.",
        "- The logged Sindri GPU runs on a 16 GiB V100 used g = 8 at 2^22 and g = 5 at 2^24, the "
        "largest that fit.",
        "",
        "| n | "
        + " | ".join(f"{b} GiB: g" for b in BUDGETS_GIB)
        + " | "
        + " | ".join(f"{b} GiB: field mults" for b in BUDGETS_GIB)
        + " | Pippenger: field mults |",
        "|---|" + "---|" * (2 * len(BUDGETS_GIB) + 1),
    ]
    for log_n in sizes:
        at = {r.budget_gib: r for r in rows if r.log_n == log_n}
        gs = [
            f"{at[b].g}" + (f" ({at[b].memory_g})" if at[b].memory_g > at[b].g else "")
            if at[b].g
            else "doesn't fit"
            for b in BUDGETS_GIB
        ]
        mults = [f"{at[b].sagittal_mults:,.0f}" if at[b].g else "-" for b in BUDGETS_GIB]
        pip = at[BUDGETS_GIB[0]]
        lines.append(
            f"| 2^{log_n} | "
            + " | ".join(gs)
            + " | "
            + " | ".join(mults)
            + f" | {pip.pippenger_mults:,.0f} (c = {pip.pippenger_c}) |"
        )
    path.write_text("\n".join(lines) + "\n")


def plot(path: Path, rows: list[Row], curve: CurveParams) -> None:
    import matplotlib

    matplotlib.use("Agg")  # render to files, no window
    import matplotlib.pyplot as plt

    plt.rcParams.update(
        {
            "text.color": TEXT_PRIMARY,
            "axes.labelcolor": TEXT_SECONDARY,
            "xtick.color": TEXT_SECONDARY,
            "ytick.color": TEXT_SECONDARY,
            "axes.edgecolor": GRID,
        }
    )
    fig, ax = plt.subplots(figsize=(8, 5), dpi=150, facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    sizes = sorted({r.log_n for r in rows})
    series: list[tuple[str, str, list[int], list[float], list[str]]] = []
    for budget in CHARTED_GIB:
        pts = [r for r in rows if r.budget_gib == budget and r.g]
        series.append(
            (
                f"Sagittal, {budget} GiB GPU (largest g that fits)",
                f"Sagittal, {budget} GiB",
                [r.log_n for r in pts],
                [r.sagittal_mults for r in pts],
                [f"g={r.g}" for r in pts],
            )
        )
    pip = [r for r in rows if r.budget_gib == BUDGETS_GIB[0]]
    series.append(
        (
            "Pippenger, signed digits (best c)",
            "Pippenger",
            [r.log_n for r in pip],
            [r.pippenger_mults for r in pip],
            [],
        )
    )
    label_dy = {0: -12, 1: -7, 2: 0}
    for i, ((label, short, x, y, notes), color) in enumerate(zip(series, SERIES, strict=True)):
        # The 16 GiB line (with its g labels) draws on top where the Sagittal lines coincide.
        ax.plot(
            x,
            y,
            color=color,
            linewidth=1.5,
            marker="o",
            markersize=5,
            label=label,
            zorder=3 if i == 0 else 2,
        )
        ax.annotate(
            short,
            (x[-1], y[-1]),
            xytext=(8, label_dy[i]),
            textcoords="offset points",
            va="center",
            fontsize=9,
            color=TEXT_SECONDARY,
        )
        if i == 0:  # g values on the 16 GiB line, where the steps happen
            for xi, yi, note in zip(x, y, notes, strict=True):
                ax.annotate(
                    note,
                    (xi, yi),
                    xytext=(0, 7),
                    textcoords="offset points",
                    ha="center",
                    fontsize=7,
                    color=TEXT_SECONDARY,
                )
    ax.set_xticks(sizes, [f"$2^{{{s}}}$" for s in sizes])
    ax.set_xlim(sizes[0] - 0.5, sizes[-1] + 2.2)
    ax.set_ylim(0, None)
    ax.yaxis.set_major_formatter(lambda value, _: f"{value:,.0f}")
    ax.set_title(
        f"Per-proof field multiplications per point under GPU memory limits ({curve.name})",
        fontsize=11,
    )
    ax.set_xlabel("MSM size, n (points)")
    ax.set_ylabel("Field multiplications per point (XYZZ)")
    ax.grid(True, which="major", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.legend(frameon=False, loc="upper left")
    fig.tight_layout()
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--curve", choices=[c.name for c in CURVES], default="bls12-377")
    parser.add_argument("--min-log-n", type=int, default=16)
    parser.add_argument("--max-log-n", type=int, default=26)
    parser.add_argument("--out", type=Path, default=Path(__file__).parent / "results")
    args = parser.parse_args()

    curve = next(c for c in CURVES if c.name == args.curve)
    rows = compute(curve, range(args.min_log_n, args.max_log_n + 1))
    args.out.mkdir(parents=True, exist_ok=True)
    write_csv(args.out / "memory.csv", rows)
    write_markdown(args.out / "memory.md", rows, curve)
    plot(args.out / "memory.png", rows, curve)
    print(f"Wrote memory.csv, memory.md, and memory.png to {args.out}")


if __name__ == "__main__":
    main()
