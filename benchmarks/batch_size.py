"""Count Sagittal MSM operations for each batch size g, against naive double-and-add.

Runs every algorithm on the counting group (exact add/double counts, no curve arithmetic)
and reports operations per input point, so the numbers don't depend on n. Writes to the
output directory:

- batch_size.csv   measured counts per phase for each g, plus the naive baseline
- batch_size.md    Markdown table of the same, with the closed-form prediction
- batch_size.png   operations per point vs. g (log scale)

Usage: uv run python benchmarks/batch_size.py [--log-n 12] [--max-batch 12] [--group mock-bls12-377]
"""

import argparse
import csv
from dataclasses import dataclass
from pathlib import Path

from sagittal_msm.groups import GROUPS, get_group
from sagittal_msm.inputs import expected_msm, random_points, random_scalars
from sagittal_msm.msm import naive, sagittal

# Chart colors: categorical slots 1-3 and text/surface tokens of the dataviz reference palette
# (validated as a set, light mode). Text never wears a series color.
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]
SURFACE = "#fcfcfb"
TEXT_PRIMARY = "#0b0b0b"
TEXT_SECONDARY = "#52514e"
GRID = "#e4e3df"


@dataclass
class Row:
    batch_size: int
    prepare_adds: int
    accumulate_adds: int
    combine_adds: int
    combine_doubles: int
    table_points: int

    @property
    def per_proof(self) -> int:
        return self.accumulate_adds + self.combine_adds + self.combine_doubles


def predicted_accumulate_per_point(bits: int, g: int) -> float:
    """Expected mixed adds per point: each of the b bit columns of a batch is nonzero with
    probability 1 - 2^-g, and there are n/g batches."""
    return bits * (1 - 2.0**-g) / g


def measure(group_name: str, n: int, max_batch: int) -> tuple[list[Row], int, int]:
    group = get_group(group_name)
    points = random_points(group, n)
    scalars = random_scalars(group, n)
    want = expected_msm(group, points, scalars)

    rows = []
    for g in range(1, max_batch + 1):
        group.counter.reset()
        tables = sagittal.prepare(group, points, g)
        assert group.eq(sagittal.msm(group, tables, scalars), want)
        c = group.counter
        rows.append(
            Row(
                batch_size=g,
                prepare_adds=c.total("add", "prepare"),
                accumulate_adds=c.total("add_mixed", "accumulate"),
                combine_adds=c.total("add", "combine"),
                combine_doubles=c.total("double", "combine"),
                table_points=sum(len(t) for t in tables.tables),
            )
        )
        print(f"g={g:2d}  per-proof ops {rows[-1].per_proof:>10,}", flush=True)

    group.counter.reset()
    assert group.eq(naive.msm(group, points, scalars), want)
    return rows, group.counter.total(), group.scalar_bits


def write_csv(path: Path, rows: list[Row], naive_ops: int) -> None:
    with path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(
            ["algorithm", "batch_size", "prepare_adds", "accumulate_adds", "combine_adds",
             "combine_doubles", "per_proof_ops", "table_points"]
        )  # fmt: skip
        for r in rows:
            writer.writerow(
                ["sagittal", r.batch_size, r.prepare_adds, r.accumulate_adds, r.combine_adds,
                 r.combine_doubles, r.per_proof, r.table_points]
            )  # fmt: skip
        writer.writerow(["naive", "", 0, "", "", "", naive_ops, 0])


def write_markdown(
    path: Path, rows: list[Row], naive_ops: int, n: int, bits: int, group_name: str
) -> None:
    lines = [
        f"Sagittal MSM operation counts on `{group_name}` ({bits}-bit scalars), n = {n:,} "
        "points. Generated by `benchmarks/batch_size.py`.",
        "",
        "- **Per proof** = accumulate mixed adds + combine adds and doubles.",
        "- **Predicted** = b * (1 - 2^-g) / g accumulate adds per point.",
        "- **Precompute** is paid once per set of points (the proving key) and reused.",
        f"- **Naive** double-and-add for the same input: {naive_ops / n:,.1f} ops per point.",
        "",
        "| g | Per proof, ops/point | Predicted accumulate/point | Precompute adds/point "
        "| Table size (x n points) |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r.batch_size} | {r.per_proof / n:,.2f} "
            f"| {predicted_accumulate_per_point(bits, r.batch_size):,.2f} "
            f"| {r.prepare_adds / n:,.2f} | {r.table_points / n:,.1f} |"
        )
    path.write_text("\n".join(lines) + "\n")


def plot(path: Path, rows: list[Row], naive_ops: int, n: int, bits: int) -> None:
    import matplotlib

    matplotlib.use("Agg")  # render to files, no window
    import matplotlib.pyplot as plt

    x = [r.batch_size for r in rows]
    # g = 1 needs no precompute; a log axis can't show 0, so that point is left out.
    series = {
        "Per proof (accumulate + combine)": [r.per_proof / n for r in rows],
        "Precompute, once per proving key": [r.prepare_adds / n or float("nan") for r in rows],
        "Naive double-and-add, per proof": [naive_ops / n] * len(rows),
    }
    # Direct-label offsets (points) so end labels that meet at the right edge don't collide.
    label_dy = {"Per proof": 0, "Precompute": -9, "Naive double-and-add": 7}

    plt.rcParams.update(
        {
            "text.color": TEXT_PRIMARY,
            "axes.labelcolor": TEXT_SECONDARY,
            "xtick.color": TEXT_SECONDARY,
            "ytick.color": TEXT_SECONDARY,
            "axes.edgecolor": GRID,
        }
    )
    fig, ax = plt.subplots(figsize=(8, 5), dpi=150, facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    for (label, values), color in zip(series.items(), SERIES, strict=True):
        is_baseline = label.startswith("Naive")
        ax.plot(
            x,
            values,
            color=color,
            linewidth=1.5,
            linestyle="--" if is_baseline else "-",
            marker=None if is_baseline else "o",
            markersize=5,
            label=label,
        )
        # Direct label at the right end, in text ink; the line beside it carries the color.
        short = label.split(",")[0].split(" (")[0]
        ax.annotate(
            short,
            (x[-1], values[-1]),
            xytext=(8, label_dy[short]),
            textcoords="offset points",
            va="center",
            fontsize=9,
            color=TEXT_SECONDARY,
        )
    ax.set_yscale("log")
    ax.set_xticks(x)
    ax.yaxis.set_major_formatter(lambda value, _: f"{value:,.0f}" if value >= 1 else f"{value:g}")
    ax.set_xlim(x[0] - 0.5, x[-1] + 2.8)  # room for the direct labels
    ax.set_title(f"Sagittal MSM: EC operations per point by batch size ({bits}-bit scalars)")
    ax.set_xlabel("Batch size, g (points per subset-sum table)")
    ax.set_ylabel("EC operations per point (log scale)")
    ax.grid(True, which="major", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.legend(frameon=False, loc="lower right")
    fig.tight_layout()
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--log-n", type=int, default=12, help="number of points is 2^log_n")
    parser.add_argument("--max-batch", type=int, default=12)
    parser.add_argument("--group", choices=sorted(GROUPS), default="mock-bls12-377")
    parser.add_argument("--out", type=Path, default=Path(__file__).parent / "results")
    args = parser.parse_args()

    n = 1 << args.log_n
    rows, naive_ops, bits = measure(args.group, n, args.max_batch)

    args.out.mkdir(parents=True, exist_ok=True)
    write_csv(args.out / "batch_size.csv", rows, naive_ops)
    write_markdown(args.out / "batch_size.md", rows, naive_ops, n, bits, args.group)
    plot(args.out / "batch_size.png", rows, naive_ops, n, bits)
    print(f"Wrote batch_size.csv, batch_size.md, and batch_size.png to {args.out}")


if __name__ == "__main__":
    main()
