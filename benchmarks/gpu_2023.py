"""Chart and tabulate the May 2023 GPU benchmark of Sindri's CUDA Sagittal MSM against the
ZPrize 2022 GPU MSM entries (BLS12-377, one GPU, one MSM per timed run).

Reads benchmarks/data/gpu_2023.csv, transcribed from the raw benchmark logs:

- ZPrize entries: criterion medians from each entry's own benchmark harness. Each entry's
  one-time setup (`multi_scalar_mult_init`: copying points, and for Yrrid and MatterLabs + Yrrid
  precomputing shifted points) runs before timing starts.
- Sagittal and Supranational sppark: the MAIN time of Sindri's `msm_bench` (a single timed run
  after the separate one-time PREPARE step).
- Yrrid and MatterLabs + Yrrid require an Ampere GPU (compute capability 8.0) and were not
  run on the V100.

Writes:

- gpu_2023.md    every logged result by GPU and size
- gpu_2023.png   2^20 results on both GPUs

Usage: uv run python benchmarks/gpu_2023.py
"""

import argparse
import csv
from dataclasses import dataclass
from pathlib import Path

SAGITTAL_COLOR = "#2a78d6"  # categorical slot 1 of the dataviz reference palette
OTHER_COLOR = "#b4b2aa"  # neutral for the comparison entries
SURFACE = "#fcfcfb"
TEXT_PRIMARY = "#0b0b0b"
TEXT_SECONDARY = "#52514e"
GRID = "#e4e3df"
GPUS = ["V100", "A10G"]
GPU_NAMES = {"V100": "Tesla V100-SXM2 16 GB", "A10G": "NVIDIA A10G 24 GB"}


@dataclass
class Result:
    gpu: str
    entry: str
    log_n: int
    ms: float
    config: str
    note: str


def load(path: Path) -> list[Result]:
    with path.open() as f:
        return [
            Result(
                row["gpu"],
                row["entry"],
                int(row["log_n"]),
                float(row["ms"]),
                row["config"],
                row["note"],
            )
            for row in csv.DictReader(f)
        ]


def write_markdown(path: Path, results: list[Result]) -> None:
    sizes = sorted({x.log_n for x in results})
    lines = [
        "MSM time in milliseconds, BLS12-377, one GPU, May 2023. Generated by "
        "`benchmarks/gpu_2023.py` from `benchmarks/data/gpu_2023.csv`; the docstring there "
        "describes how each number was measured. Fastest per column in bold.",
        "",
    ]
    for gpu in GPUS:
        rows = [x for x in results if x.gpu == gpu]
        entries = sorted({x.entry for x in rows}, key=lambda e: e != "Sagittal (Sindri)")
        best = {s: min(x.ms for x in rows if x.log_n == s) for s in sizes}
        lines += [
            f"### {GPU_NAMES[gpu]}",
            "",
            "| Entry | " + " | ".join(f"2^{s}" for s in sizes) + " |",
            "|---|" + "---|" * len(sizes),
        ]
        notes = []
        for entry in entries:
            cells = []
            for s in sizes:
                match = [x for x in rows if x.entry == entry and x.log_n == s]
                if not match:
                    cells.append("—")
                    continue
                x = match[0]
                cell = f"{x.ms:,.0f}"
                cell = f"**{cell}**" if x.ms == best[s] else cell
                if x.config:
                    cell += f" ({x.config})"
                if x.note:
                    notes.append(f"{entry} at 2^{s}: {x.note}.")
                    cell += "*"
                cells.append(cell)
            lines.append(f"| {entry} | " + " | ".join(cells) + " |")
        if gpu == "V100":
            notes.append(
                "Sagittal at 2^24: no completed run was logged. Yrrid and MatterLabs + "
                "Yrrid require an Ampere GPU and did not run on the V100."
            )
        lines += [""] + [f"\\* {note}" if "failed" in note else note for note in notes] + [""]
    path.write_text("\n".join(lines))


def plot(path: Path, results: list[Result]) -> None:
    import matplotlib

    matplotlib.use("Agg")  # render to files, no window
    import matplotlib.pyplot as plt

    plt.rcParams.update(
        {
            "text.color": TEXT_PRIMARY,
            "axes.labelcolor": TEXT_SECONDARY,
            "xtick.color": TEXT_SECONDARY,
            "ytick.color": TEXT_SECONDARY,
            "axes.edgecolor": GRID,
        }
    )
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), dpi=150, facecolor=SURFACE, sharex=True)
    for ax, gpu in zip(axes, GPUS, strict=True):
        ax.set_facecolor(SURFACE)
        rows = sorted((x for x in results if x.gpu == gpu and x.log_n == 20), key=lambda x: -x.ms)
        colors = [SAGITTAL_COLOR if x.entry.startswith("Sagittal") else OTHER_COLOR for x in rows]
        ax.barh([x.entry for x in rows], [x.ms for x in rows], color=colors, height=0.62)
        for y, x in enumerate(rows):
            ax.text(x.ms + 6, y, f"{x.ms:,.0f} ms", va="center", fontsize=8.5, color=TEXT_PRIMARY)
        ax.set_title(GPU_NAMES[gpu], fontsize=10, loc="left", color=TEXT_PRIMARY)
        ax.grid(True, axis="x", color=GRID, linewidth=0.8)
        ax.set_axisbelow(True)
        ax.tick_params(axis="y", length=0, labelsize=9)
        for side in ("top", "right", "left"):
            ax.spines[side].set_visible(False)
        ax.set_xlabel("MSM time, ms (lower is better)")
    fig.text(
        0.01,
        0.015,
        "Yrrid and MatterLabs + Yrrid require Ampere GPUs and were not run on "
        "the V100. Setup and precompute are excluded for every entry.",
        fontsize=8,
        color=TEXT_SECONDARY,
    )
    axes[0].set_xlim(0, 600)
    fig.suptitle(
        "MSM at $2^{20}$ points, BLS12-377, one GPU (May 2023)",
        fontsize=12,
        x=0.01,
        ha="left",
        color=TEXT_PRIMARY,
    )
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    here = Path(__file__).parent
    parser.add_argument("--data", type=Path, default=here / "data" / "gpu_2023.csv")
    parser.add_argument("--out", type=Path, default=here / "results")
    args = parser.parse_args()

    results = load(args.data)
    args.out.mkdir(parents=True, exist_ok=True)
    write_markdown(args.out / "gpu_2023.md", results)
    plot(args.out / "gpu_2023.png", results)
    print(f"Wrote gpu_2023.md and gpu_2023.png to {args.out}")


if __name__ == "__main__":
    main()
